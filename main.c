#include "minishell.h"

int	main(int ac, char **av, char **env)
{
	char	args[100];

	(void)env;
	init_shell();
	while (1)
	{
		if (loop_pwd(args))
			continue ;
		cmd_parsing(args, ac);
		cmd_process(av);
	}
	wait(0);
	return (0);
}
